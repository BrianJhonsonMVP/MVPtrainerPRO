/**
 * Genera una rutina de entrenamiento usando nuestro backend (Gemini AI).
 */
export const generateWorkoutRoutine = async (
  client: Client,
  language: GeminiOutputLanguage = "es"
): Promise<Partial<Routine> | null> => {
  try {
    geminiLog("Calling Gemini workout");
    const response = await postGeminiRequest("/api/generate-workout", { clientData: client, language: normalizeLanguage(language) });

    if (!response.ok) {
      throw new Error(await getResponseErrorMessage(response));
    }
    
    const data = await response.json();
    lastGeminiErrorMessage = "";
    geminiLog("Gemini workout success");
    const normalized = normalizeRoutine(data, language);
    const hasExercises = normalized.exercises && normalized.exercises.length > 0;
    if (!hasExercises) {
      throw new Error("Gemini workout response incomplete: no exercises");
    }
    if (!Array.isArray(normalized.days) || normalized.days.length < 7) {
      throw new Error("Gemini workout response incomplete: weekly plan missing");
    }
    return {
      ...normalized,
      version: 1,
      source: "ai"
    };

  } catch (error) {
    lastGeminiErrorMessage = getGeminiFailureMessage(error);
    geminiError("Gemini failed, reason:", error);
    return null;
  }
};

/**
 * Genera un plan de dieta usando nuestro backend (Gemini AI).
 */
export const generateDietPlan = async (
  client: Client,
  language: GeminiOutputLanguage = "es"
): Promise<DietPlan | null> => {
  try {
    geminiLog("Calling Gemini diet");
    const response = await postGeminiRequest("/api/generate-diet", { clientData: client, language: normalizeLanguage(language) });

    if (!response.ok) {
      throw new Error(await getResponseErrorMessage(response));
    }

    const data = await response.json();
    lastGeminiErrorMessage = "";
    geminiLog("Gemini diet success");
    const hasSevenDays = Array.isArray(data.days) && data.days.length >= 7;
    if (!hasSevenDays) {
      throw new Error("Gemini diet response incomplete: 7 days required");
    }
    const normalized = normalizeDiet(data, language);
    return {
      ...normalized,
      version: 1,
      source: "ai"
    };

  } catch (error) {
    lastGeminiErrorMessage = getGeminiFailureMessage(error);
    geminiError("Gemini failed, reason:", error);
    return null;
  }
};
