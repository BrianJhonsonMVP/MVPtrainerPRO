/**
 * Asegura que la rutina tenga el formato esperado por el frontend
 */
export const normalizeRoutine = (data: any, language: GeminiOutputLanguage = "es"): Partial<Routine> => {
  const copy = fallbackCopy[normalizeLanguage(language)];
  if (!data) return { name: copy.aiRoutineTitle, description: "", exercises: [], tags: [] };
  
  geminiLog("NORMALIZING ROUTINE START...");

  const ALL_DAYS = getDayLabels(normalizeLanguage(language));
  const dayKey = (value: any) => String(value || "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim();
  const rawDays = Array.isArray(data.days) ? data.days : [];
  const flatExercises = Array.isArray(data.exercises)
    ? [...data.exercises]
    : Array.isArray(data.workouts)
      ? [...data.workouts]
      : [];
  const flatExercisesByDay: Record<string, any[]> = Object.fromEntries(ALL_DAYS.map(day => [day, []]));

  flatExercises.forEach((exercise: any) => {
    const localizedExerciseDay = localizeDay(exercise?.day || exercise?.dayName, normalizeLanguage(language));
    const targetDay = ALL_DAYS.find(day => day === localizedExerciseDay);
    if (targetDay) flatExercisesByDay[targetDay].push({ ...exercise, day: targetDay });
  });

  const normalizedDays = ALL_DAYS.map(dayName => {
    const foundDay = rawDays.find((day: any) => localizeDay(day?.day || day?.name, normalizeLanguage(language)) === dayName || dayKey(day?.day || day?.name).includes(dayKey(dayName)));
    const structuredExercises = foundDay ? (foundDay.exercises || foundDay.workouts || []) : [];
    const dayExercises = Array.isArray(structuredExercises) && structuredExercises.length > 0
      ? structuredExercises
      : flatExercisesByDay[dayName];
    return {
      ...(foundDay || {}),
      day: dayName,
      exercises: Array.isArray(dayExercises) ? dayExercises : []
    };
  });

  let flattenedExercises = flatExercises;
  if (flattenedExercises.length === 0) {
    normalizedDays.forEach((day: any) => {
        day.exercises.forEach((ex: any) => {
            flattenedExercises.push({
                ...ex,
                day: day.day || "General"
            });
        });
    });
  }

  const normalized = {
    name: data.title || data.name || copy.aiRoutineTitle,
    description: data.summary || data.description || data.notes || copy.aiRoutineSummary,
    title: data.title || data.name || copy.aiRoutineTitle,
    summary: data.summary || data.description || copy.aiRoutineSummary,
    exercises: flattenedExercises,
    days: normalizedDays,
    tags: Array.isArray(data.tags) ? data.tags : ["ai"],
    warnings: Array.isArray(data.warnings) ? data.warnings : [],
    recommendations: Array.isArray(data.recommendations) ? data.recommendations : []
  };

  geminiLog("NORMALIZED ROUTINE EXERCISES COUNT:", normalized.exercises.length);
  return normalized;
};

